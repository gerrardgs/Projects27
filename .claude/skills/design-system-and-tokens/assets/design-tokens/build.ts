// Builds dist/tokens.css from tokens/resolver.json (DTCG Resolver Module 2025.10) and fails when a contrast pair
// misses its WCAG minimum in any theme.
// Usage: node build.ts            write dist/tokens.css and report contrast
//        node build.ts --check    report only; exit 1 on any failure (for CI)

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { contextsOf, parseResolver, resolveTokens, safeTokenPath } from "./resolver.ts";
import { type ContrastPair, type ContrastResult, checkContrast, cssDeclarations, type FlatToken } from "./tokens.ts";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const TOKEN_DIR = path.join(ROOT, "tokens");
const THEME_MODIFIER = "theme";

async function readJson(relativePath: string): Promise<unknown> {
  return JSON.parse(await readFile(path.join(ROOT, relativePath), "utf8"));
}

function parsePairs(raw: unknown): ContrastPair[] {
  const pairs = typeof raw === "object" && raw !== null && "pairs" in raw ? raw.pairs : undefined;
  if (!Array.isArray(pairs)) throw new Error('contrast-pairs.json: expected a "pairs" array');
  return pairs.map((pair: unknown, index) => {
    if (typeof pair !== "object" || pair === null) throw new Error(`contrast pair ${index}: expected an object`);
    const { foreground, background, minimum }: { foreground?: unknown; background?: unknown; minimum?: unknown } = pair;
    if (typeof foreground !== "string" || typeof background !== "string" || typeof minimum !== "number") {
      throw new Error(`contrast pair ${index}: needs foreground, background (strings) and minimum (number)`);
    }
    return { foreground, background, minimum };
  });
}

/** Every theme must define exactly the same semantic token paths, or components break in one theme. */
function assertSameShape(themes: ReadonlyMap<string, ReadonlyMap<string, FlatToken>>): void {
  const shape = (tokens: ReadonlyMap<string, FlatToken>) => [...tokens.keys()].sort().join("\n");
  const [[first, firstTokens] = ["", new Map()], ...rest] = [...themes];
  for (const [theme, tokens] of rest) {
    if (shape(tokens) !== shape(firstTokens))
      throw new Error(`theme "${theme}" does not define the same tokens as "${first}"`);
  }
}

const indent = (lines: string[], depth: number): string =>
  lines.map((line) => `${"  ".repeat(depth)}${line}`).join("\n");
const isTheme = (tokenPath: string): boolean => tokenPath.startsWith("theme.");

/**
 * The default theme sets every variable on :root. A "dark" theme also follows the OS setting unless the page forces
 * a theme with data-theme; every other theme applies through data-theme only.
 */
function renderCss(themes: ReadonlyMap<string, ReadonlyMap<string, FlatToken>>, defaultTheme: string): string {
  const blocks = [...themes]
    .filter(([name]) => name !== defaultTheme)
    .map(([name, tokens]) => {
      const scheme = name === "dark" ? "dark" : "light";
      const forced = `:root[data-theme="${name}"] {\n${indent(cssDeclarations(tokens, isTheme), 1)}\n  color-scheme: ${scheme};\n}`;
      if (name !== "dark") return forced;
      const system = `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="${defaultTheme}"]) {\n${indent(cssDeclarations(tokens, isTheme), 2)}\n    color-scheme: dark;\n  }\n}`;
      return `${system}\n\n${forced}`;
    });
  const defaults = themes.get(defaultTheme) ?? new Map();
  return `/* Generated by build.ts from tokens/resolver.json. Do not edit by hand. */
:root {
${indent(
  cssDeclarations(defaults, (tokenPath) => !isTheme(tokenPath)),
  1,
)}
${indent(cssDeclarations(defaults, isTheme), 1)}
  color-scheme: ${defaultTheme === "dark" ? "dark" : "light"};
}

${blocks.join("\n\n")}
`;
}

export interface BuildResult {
  readonly css: string;
  readonly contrast: ReadonlyMap<string, ContrastResult[]>;
}

export async function build(): Promise<BuildResult> {
  const resolver = parseResolver(await readJson("tokens/resolver.json"));
  const load = async (ref: string) => JSON.parse(await readFile(safeTokenPath(TOKEN_DIR, ref, path.join), "utf8"));
  const names = contextsOf(resolver, THEME_MODIFIER);
  const themes = new Map<string, ReadonlyMap<string, FlatToken>>();
  for (const name of names) themes.set(name, await resolveTokens(resolver, { [THEME_MODIFIER]: name }, load));
  assertSameShape(themes);
  const pairs = parsePairs(await readJson("contrast-pairs.json"));
  const contrast = new Map([...themes].map(([name, tokens]) => [name, checkContrast(tokens, pairs)]));
  return { css: renderCss(themes, names[0] ?? "light"), contrast };
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes("--check");
  const { css, contrast } = await build();
  let failures = 0;
  for (const [theme, results] of contrast) {
    for (const result of results) {
      const status = result.passes ? "pass" : "FAIL";
      if (!result.passes) failures += 1;
      console.log(
        `${status} ${theme.padEnd(5)} ${result.ratio.toFixed(2).padStart(5)}:1 (min ${result.minimum}) ${result.foreground} on ${result.background}`,
      );
    }
  }
  if (!checkOnly) {
    await mkdir(path.join(ROOT, "dist"), { recursive: true });
    await writeFile(path.join(ROOT, "dist", "tokens.css"), css);
    console.log("wrote dist/tokens.css");
  }
  console.log(`${failures} contrast failure(s)`);
  process.exitCode = failures > 0 ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
